def _rename_keys(value, mapping):
    if isinstance(value, dict):
        return {mapping.get(k, k): _rename_keys(v, mapping) for k, v in value.items()}
    if isinstance(value, list):
        return [_rename_keys(v, mapping) for v in value]
    return value


def _rewrite_json(table: str, column: str, mapping: dict) -> None:
    bind = op.get_bind()
    tbl = sa.table(table, sa.column("id", sa.Integer), sa.column(column, sa.JSON))
    rows = bind.execute(sa.select(tbl.c.id, tbl.c[column])).fetchall()
    for row_id, value in rows:
        if value is None:
            continue
        new = _rename_keys(value, mapping)
        if new != value:
            bind.execute(tbl.update().where(tbl.c.id == row_id).values({column: new}))


